/**
 * Busca DTCs en la base de datos por código o descripción
 * @param {string} query - Término de búsqueda
 * @param {number} limit - Número máximo de resultados
 */
export function searchDTC(query, limit = 15) {
  if (!query || query.trim().length < 2) return [];
  const q = query.trim().toUpperCase();
  return DTC_DATABASE.filter(d =>
    d.code.includes(q) ||
    d.desc.toUpperCase().includes(q) ||
    d.system.toUpperCase().includes(q)
  ).slice(0, limit);
}

/**
 * Obtiene un DTC específico por código exacto
 */
export function getDTCByCode(code) {
  return DTC_DATABASE.find(d => d.code === code.trim().toUpperCase()) || null;
}

